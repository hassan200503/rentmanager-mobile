#!/usr/bin/env node
/**
 * Generates src/api/schema.d.ts from the backend's OpenAPI document.
 *
 *   npm run api:types              fetch from OPENAPI_URL (default local backend),
 *                                  save the snapshot, regenerate types
 *   npm run api:types -- --offline regenerate from the committed snapshot only
 *   npm run api:check              fail if the committed types are stale against
 *                                  the committed snapshot (CI drift gate), or,
 *                                  with OPENAPI_URL set, against a live backend
 *
 * The snapshot (openapi/rentmanager.json) is committed so a type change is
 * reviewable as a diff and CI does not need a running backend.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const snapshotPath = join(root, 'openapi', 'rentmanager.json');
const typesPath = join(root, 'src', 'api', 'schema.d.ts');
const args = new Set(process.argv.slice(2));
const check = args.has('--check');
const offline = args.has('--offline') || (check && !process.env.OPENAPI_URL);
const url = process.env.OPENAPI_URL ?? 'http://localhost:8080/v3/api-docs';

function normalise(spec) {
  // Server URLs differ per environment and would churn the snapshot.
  const copy = { ...spec };
  delete copy.servers;
  return JSON.stringify(copy, null, 2) + '\n';
}

async function loadSpec() {
  if (offline) {
    if (!existsSync(snapshotPath)) throw new Error(`No snapshot at ${snapshotPath}`);
    return readFileSync(snapshotPath, 'utf8');
  }
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return normalise(await res.json());
}

function generate(specText) {
  const dir = mkdtempSync(join(tmpdir(), 'rm-openapi-'));
  const specFile = join(dir, 'spec.json');
  const outFile = join(dir, 'schema.d.ts');
  writeFileSync(specFile, specText);
  const bin = join(root, 'node_modules', 'openapi-typescript', 'bin', 'cli.js');
  execFileSync(process.execPath, [bin, specFile, '-o', outFile], { stdio: 'pipe' });
  const header = '/* eslint-disable */\n// GENERATED by scripts/generate-api-types.mjs from openapi/rentmanager.json. Do not edit.\n';
  return header + readFileSync(outFile, 'utf8');
}

const specText = await loadSpec();
const types = generate(specText);

if (check) {
  const currentTypes = existsSync(typesPath) ? readFileSync(typesPath, 'utf8') : '';
  const currentSnapshot = existsSync(snapshotPath) ? readFileSync(snapshotPath, 'utf8') : '';
  const stale = [];
  if (!offline && currentSnapshot !== specText) stale.push('openapi/rentmanager.json (backend contract changed)');
  if (currentTypes !== types) stale.push('src/api/schema.d.ts');
  if (stale.length) {
    console.error(`API contract drift detected:\n  - ${stale.join('\n  - ')}\nRun "npm run api:types" and review the diff.`);
    process.exit(1);
  }
  console.log('API types are up to date.');
} else {
  if (!offline) writeFileSync(snapshotPath, specText);
  writeFileSync(typesPath, types);
  console.log(`Wrote ${typesPath}`);
}
